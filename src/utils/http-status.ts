import { NextResponse } from 'next/server'

export type ApiErrorReason =
  | 'NOT_FOUND'
  | 'POST_NOT_FOUND'
  | 'CATEGORY_NOT_FOUND'
  | 'TARGET_CATEGORY_NOT_FOUND'
  | 'COMMENT_NOT_FOUND'
  | 'PARENT_COMMENT_NOT_FOUND'
  | 'USER_NOT_FOUND'
  | 'UNAUTHORIZED'
  | 'FORBIDDEN'
  | 'VALIDATION_ERROR'
  | 'TITLE_REQUIRED'
  | 'SLUG_REQUIRED'
  | 'INVALID_SLUG_FORMAT'
  | 'CONTENT_REQUIRED'
  | 'SAME_CATEGORY_MERGE'
  | 'NO_DRAFT_TO_DISCARD'
  | 'CANNOT_DEMOTE_SELF'
  | 'CANNOT_BAN_SELF'
  | 'DUPLICATE_POST_SLUG'
  | 'DUPLICATE_POST_TITLE'
  | 'DUPLICATE_CATEGORY_NAME'
  | 'DUPLICATE_CATEGORY_SLUG'
  | 'RATE_LIMITED'
  | 'DATABASE_ERROR'
  | 'AI_TRANSLATION_FAILED'
  | 'INVALID_TRANSLATION_OUTPUT'
  | 'DELIVERY_FAILED'
  | 'UNKNOWN_ERROR'

export const HTTP_STATUS_BY_REASON = {
  NOT_FOUND: 404,
  POST_NOT_FOUND: 404,
  CATEGORY_NOT_FOUND: 404,
  TARGET_CATEGORY_NOT_FOUND: 404,
  COMMENT_NOT_FOUND: 404,
  PARENT_COMMENT_NOT_FOUND: 404,
  USER_NOT_FOUND: 404,
  UNAUTHORIZED: 401,
  FORBIDDEN: 403,
  CANNOT_DEMOTE_SELF: 403,
  CANNOT_BAN_SELF: 403,
  VALIDATION_ERROR: 400,
  TITLE_REQUIRED: 400,
  SLUG_REQUIRED: 400,
  INVALID_SLUG_FORMAT: 400,
  CONTENT_REQUIRED: 400,
  SAME_CATEGORY_MERGE: 400,
  NO_DRAFT_TO_DISCARD: 400,
  DUPLICATE_POST_SLUG: 409,
  DUPLICATE_POST_TITLE: 409,
  DUPLICATE_CATEGORY_NAME: 409,
  DUPLICATE_CATEGORY_SLUG: 409,
  RATE_LIMITED: 429,
  DATABASE_ERROR: 500,
  AI_TRANSLATION_FAILED: 502,
  INVALID_TRANSLATION_OUTPUT: 502,
  DELIVERY_FAILED: 502,
  UNKNOWN_ERROR: 500,
} as const satisfies Record<ApiErrorReason, number>

export function handleApiError(err: { reason: ApiErrorReason; details?: unknown }) {
  const status = HTTP_STATUS_BY_REASON[err.reason]
  return NextResponse.json({ success: false, error: err.reason }, { status })
}
